    Route::get('/api-proxy/contractors', [ProxyController::class, 'getContractors'])->name('proxy.contractors');
    Route::get('/api-proxy/reports/transactions/{id}', [ProxyController::class, 'getProjectTransactions'])->name('proxy.report.transactions');
